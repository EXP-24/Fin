const LanguageContext = createContext();

export const LanguageProvider = ({ children }) => {
  const [lang, setLang] = useState(localStorage.getItem("lang") || "VN");

  useEffect(() => {
    localStorage.setItem("lang", lang);
  }, [lang]);

  const t = (key) => {
    return translations[lang]?.[key] || key;
  };

  // Inline pair: tr("Tiếng Việt", "English"). Use t("key") only for strings kept in the dictionary above.
  const tr = (vn, en) => (lang === "VN" ? vn : en);

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, tr }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
